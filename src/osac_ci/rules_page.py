"""The rules page: how a pull request merges and what decides it, written from ``policy/flow.yml``.

The page (``docs/RULES.md``) is generated, never edited by hand: ``osac-ci explain-rules --output docs/RULES.md``
rewrites it and ``--check`` fails when it is stale, so what a reader sees is always what the code applies. The values
(who may approve, which bots, which files) come from the rules file; the prose around them is fixed here. A repository's
own suites can be added to the page with ``--policy``; that part is per repository and is not committed in osac-ci.
"""

from __future__ import annotations

from collections.abc import Sequence

from osac_ci.flow import Flow
from osac_ci.policy import Policy

PAGE_PATH = "docs/RULES.md"


def _code_list(values: Sequence[str]) -> str:
    return ", ".join(f"`{v}`" for v in values)


def _bullets(values: Sequence[str]) -> str:
    return "\n".join(f"- `{v}`" for v in values)


def render_rules(rules: Flow, policies: Sequence[Policy] = ()) -> str:
    """The page as markdown. The output is deterministic: the same rules always give the same bytes."""
    approval = rules.approval
    checks = rules.checks
    bot = rules.bot_approve
    parts = [
        f"""<!-- Generated by `osac-ci explain-rules` from policy/flow.yml. Do not edit by hand: change the rules
        file and \
regenerate. -->
# How a pull request merges

This page says what decides whether a pull request starts its expensive tests and merges, in every repository that uses
the shared flow of osac-ci (osac, osac-test-infra, ...). It is generated from
[`policy/flow.yml`](../policy/flow.yml), so
it cannot drift from what the code applies.

## The path of a pull request

1. The author opens a pull request. Two required checks run at once: `CI` (the repository's own tests and lint, summed
   up by one job) and `jira-reference` (the title names a Jira issue, or says `NO-ISSUE:`). `jira-reference` says
   nothing about the quality of the change, so the E2E does not count it (see "Checks that do not count as cheap").
2. A person approves, or CodeRabbit does for a branch of the repository itself (see below). The approval is for the
   exact
   commit; a push dismisses it.
3. The full-install tests (the `E2E` check, with one line per suite) start from the default branch's copy of the
   workflow, for the approved commit. They do not wait for `CI`; they do not start when another required check has
   failed.
4. Auto-merge is switched on for an approved pull request (with the OSAC CI app's token, so that what follows starts
   its workflows). GitHub puts the pull request in the merge queue once every required check and the approval are in
   place.
5. The merge queue runs `CI` and `E2E` once more on the exact commit that will land and merges it.

## Who may start the E2E

The E2E runs the pull request's code with the repository's secrets, so only an approval of the **head commit**
counts, and
only from:

- a person whose **effective permission on the repository** is one of: {_code_list(approval.write_permissions)}.
  Being a member of the organization, or a collaborator with `triage` or `read` access, is not enough.
- on a pull request from a **branch of the repository itself**, also these bots: {_code_list(approval.trusted_bots)}.
  Never on a pull request from a **fork**: the author of a fork controls what CodeRabbit reads, so a fork needs a person
  with write access, and the run starts only after that approval.

The author cannot approve their own pull request. A push after the approval dismisses it; a rebase that changes nothing
of the pull request's own changes keeps it, a rebase with conflict resolution drops it.

## Checks that do not count as cheap

The E2E starts when no other required check has failed on the commit. These checks say nothing about the quality of the
change, so they are not counted in that test: {_code_list(checks.not_cheap)}. A repository may add names to this list
in its own policy file (`flow.checks.not_cheap_extra`); nothing else.

## Bots that are approved without a person

A dependency update by one of these bots is approved by the OSAC CI app, without a person reading it, only when
**every**
condition holds:

- the author is one of: {_code_list(bot.bots)};
- every commit is the bot's own, plain and signed; the only other committer allowed is `{bot.committer}` (GitHub signing
  for the bot);
- every changed file is a dependency file, matched on its base name. Names:

{_bullets(bot.dependency_file_names)}

  Patterns:

{_bullets(bot.dependency_file_patterns)}

A change to a workflow, a script or a source file is never approved without a person, whoever wrote it. The approval is
for the exact head commit, so a later push drops it and the next sweep looks again.

## What a repository can and cannot change

A repository keeps its own suites, path filters and tests in its own files. Of the rules on this page it may change
only:
{_code_list(rules.repository_may_extend)}. Anything else in its policy file is refused when the policy loads, so no
repository can widen who starts an E2E or what a bot approves.

## How to change a rule

Change `policy/flow.yml` in a pull request to osac-ci and regenerate this page (`osac-ci explain-rules --output
docs/RULES.md`). A test pins every value, so the change is deliberate, and `wg-infra` reviews it (CODEOWNERS).
Repositories
take the change when they move to the next osac-ci release; see [`CALLERS.md`](CALLERS.md).
"""
    ]
    if policies:
        parts.append("## Suites of each repository\n")
        for policy in sorted(policies, key=lambda p: p.repo):
            parts.append(f"### {policy.repo}\n")
            parts.append("| Suite | Line on the pull request | Runs when |")
            parts.append("|---|---|---|")
            for name, job in policy.jobs.items():
                if job.kind != "e2e":
                    continue
                must = ", ".join(f"`{f}`" for f in job.filters)
                any_of = ", ".join(f"`{f}`" for f in job.filters_any)
                include = ", ".join(f"`{g}`" for g in job.paths)
                exclude = ", ".join(f"`{g}`" for g in job.exclude_paths)
                when = "; ".join(
                    x
                    for x in (
                        f"a changed file matches {include}" if include else "",
                        f"not only files matching {exclude}" if exclude else "",
                        f"all of {must}" if must else "",
                        f"one of {any_of}" if any_of else "",
                    )
                    if x
                )
                parts.append(f"| `{job.suite or name}` | {job.check} | {when or 'always'} |")
            parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"
